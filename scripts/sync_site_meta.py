#!/usr/bin/env python3
"""Keep the search / sharing tags, the no-JavaScript fallback menu and sitemap.xml in sync.

What it does for every page (*.html in the repository root and in annuals/):
  1. Writes canonical, Open Graph, Twitter card and icon tags between
     <!-- meta:start --> and <!-- meta:end --> in <head>. The title and description are taken
     from the page's own <title> and <meta name="description">.
  2. Writes a plain-HTML copy of the menu and footer contact line inside <noscript> in the
     #site-nav and #site-footer placeholders. Crawlers that do not run JavaScript, and visitors
     with JavaScript turned off, see these links. Normal visitors never see them, because
     assets/site.js builds the real header, menu and footer.
  3. Rewrites sitemap.xml with all pages.

Run it after you add, rename or retitle a page, or change the menu:

    python3 scripts/sync_site_meta.py

It is safe to run repeatedly. To add a page to the menu, edit NAV below and in assets/site.js.
"""
import html
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = "https://www.ssci-combustion.org"
NAME = "Singapore Section of the Combustion Institute"
OG_IMAGE = SITE + "/assets/og-image.jpg"
OG_ALT = NAME + ": combustion science for decarbonization and sustainability in Singapore"
LINKEDIN = "https://www.linkedin.com/company/singapore-section-of-the-combustion-institute"
CI_SITE = "https://www.combustioninstitute.org/index.php"
EMAIL = "office@ssci-combustion.org"

# (label, page) in menu order. Keep in step with the navigation block in assets/site.js.
NAV = [
    ("Home", "index.html"),
    ("About", "about.html"),
    ("Membership", "membership.html"),
    ("Annual Meetings", "annual-meetings.html"),
    ("Webinars", "webinars.html"),
    ("Other Events", "events.html"),
    ("Young Investigator Award", "young-investigator-award.html"),
    ("Best Presentation and Poster Awards", "best-presentation-awards.html"),
    ("Collaboration", "collaboration.html"),
    ("Contact", "contacts.html"),
]

# Pages that are not listed in the sitemap or given canonical/social tags.
SKIP = {"404.html"}


def pages():
    found = sorted((p for p in ROOT.glob("*.html") if p.name not in SKIP), key=lambda p: (p.name != "index.html", p.name))
    found += sorted(p for p in (ROOT / "annuals").glob("*.html"))
    return found


def page_url(path):
    rel = path.relative_to(ROOT).as_posix()
    return SITE + "/" if rel == "index.html" else SITE + "/" + rel


def esc(text):
    return html.escape(text, quote=True)


def meta_block(path, title, desc):
    prefix = "../" if path.parent.name == "annuals" else ""
    url = page_url(path)
    lines = [
        "<!-- meta:start (generated by scripts/sync_site_meta.py) -->",
        f'<link rel="canonical" href="{url}">',
        f'<meta property="og:site_name" content="{esc(NAME)}">',
        '<meta property="og:type" content="website">',
        f'<meta property="og:title" content="{esc(title)}">',
        f'<meta property="og:description" content="{esc(desc)}">',
        f'<meta property="og:url" content="{url}">',
        f'<meta property="og:image" content="{OG_IMAGE}">',
        f'<meta property="og:image:alt" content="{esc(OG_ALT)}">',
        '<meta name="twitter:card" content="summary_large_image">',
        '<meta name="theme-color" content="#813c54">',
        '<meta name="referrer" content="strict-origin-when-cross-origin">',
        f'<link rel="icon" href="{prefix}favicon.ico" sizes="any">',
        f'<link rel="icon" type="image/png" sizes="32x32" href="{prefix}assets/favicon-32.png">',
        f'<link rel="apple-touch-icon" href="{prefix}assets/apple-touch-icon.png">',
        "<!-- meta:end -->",
    ]
    return "\n    ".join(lines)


def nav_block(path):
    prefix = "../" if path.parent.name == "annuals" else ""
    items = "".join(f'<li><a href="{prefix}{href}">{esc(label)}</a></li>' for label, href in NAV)
    return (
        '<div id="site-nav"><!-- shell:start --><noscript>'
        f'<nav aria-label="Main menu"><ul>{items}</ul></nav>'
        "</noscript><!-- shell:end --></div>"
    )


def footer_block():
    return (
        '<div id="site-footer"><!-- shell:start --><noscript><footer>'
        f"<p>{esc(NAME)}</p>"
        f'<p>Contact: <a href="mailto:{EMAIL}">{EMAIL}</a> &middot; '
        f'<a href="{LINKEDIN}">SSCI on LinkedIn</a> &middot; '
        f'<a href="{CI_SITE}">The Combustion Institute</a></p>'
        "</footer></noscript><!-- shell:end --></div>"
    )


def sync_page(path):
    text = path.read_text(encoding="utf-8")
    original = text

    title_m = re.search(r"<title>(.*?)</title>", text, re.S | re.I)
    desc_m = re.search(r'<meta\s+name=["\']description["\']\s+content=["\'](.*?)["\']', text, re.S | re.I)
    if not title_m or not desc_m:
        print(f"WARNING {path.relative_to(ROOT)}: needs a <title> and a meta description")
        return False
    title = html.unescape(" ".join(title_m.group(1).split()))
    desc = html.unescape(" ".join(desc_m.group(1).split()))

    block = meta_block(path, title, desc)
    if "<!-- meta:start" in text:
        text = re.sub(r"<!-- meta:start.*?<!-- meta:end -->", lambda m: block, text, flags=re.S)
    else:
        text = re.sub(r'\s*<link rel="shortcut icon"[^>]*>', "", text)
        text = re.sub(r"</head>", "    " + block + "\n</head>", text, count=1)

    text = re.sub(r'<div id="site-nav">.*?</div>', lambda m: nav_block(path), text, count=1, flags=re.S)
    text = re.sub(r'<div id="site-footer">.*?</div>', lambda m: footer_block(), text, count=1, flags=re.S)

    if text != original:
        path.write_text(text, encoding="utf-8")
        return True
    return False


def write_sitemap(all_pages):
    urls = "\n".join(f"  <url><loc>{page_url(p)}</loc></url>" for p in all_pages)
    (ROOT / "sitemap.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + urls + "\n</urlset>\n",
        encoding="utf-8",
    )


def main():
    all_pages = pages()
    changed = [p.relative_to(ROOT).as_posix() for p in all_pages if sync_page(p)]
    write_sitemap(all_pages)
    print(f"Pages checked: {len(all_pages)}; updated: {len(changed)}")
    for c in changed:
        print(" -", c)
    print("sitemap.xml written")


if __name__ == "__main__":
    sys.exit(main())
